import type { DataSource } from "typeorm";
import { databaseRoleName } from "../../cluster/model/cluster-names.js";
import type {
  ArtifactDatabases,
  DatabaseConnection,
} from "../interface/artifact-databases.js";

/** Where artifact pods reach the database holding every artifact's schema. */
export interface ArtifactDatabaseAddress {
  /** Host name resolvable from the artifact namespace. */
  readonly host: string;
  readonly port: number;
  /** Database holding one schema per artifact. */
  readonly database: string;
}

/** Most connections one artifact may hold, so one artifact cannot exhaust the shared server. */
const connectionLimit = 20;

/** Role names are derived from artifact IDs; passwords are generated as hexadecimal. */
const safeRole = /^artifact_[0-9a-f]{32}$/;
const safePassword = /^[0-9a-f]{32,128}$/;

/**
 * Manages artifact roles and schemas with statements PostgreSQL cannot parameterize. Names and
 * passwords are generated by this service and checked before they are quoted into SQL.
 */
export class PostgresArtifactDatabases implements ArtifactDatabases {
  // ===========================================
  // Construction
  // ===========================================

  /** Use a connection to the artifact data database as its owning role, which has CREATEROLE. */
  constructor(
    private readonly database: DataSource,
    private readonly address: ArtifactDatabaseAddress,
  ) {}

  // ===========================================
  // Operations
  // ===========================================

  /** Create or update the artifact's role and schema in one transaction. */
  async ensure(
    artifactId: string,
    password: string,
  ): Promise<DatabaseConnection> {
    const role = this.role(artifactId);
    if (!safePassword.test(password))
      throw new Error("Artifact database passwords must be hexadecimal");
    const database = this.quotedDatabase();
    await this.database.transaction(async (manager) => {
      await manager.query(
        `DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '${role}') THEN CREATE ROLE "${role}"; END IF; END $$`,
      );
      await manager.query(
        `ALTER ROLE "${role}" WITH LOGIN CONNECTION LIMIT ${connectionLimit} PASSWORD '${password}'`,
      );
      // Membership lets this service create the schema for the role and later drop what it owns.
      await manager.query(`GRANT "${role}" TO CURRENT_USER`);
      await manager.query(`GRANT CONNECT ON DATABASE ${database} TO "${role}"`);
      await manager.query(
        `CREATE SCHEMA IF NOT EXISTS "${role}" AUTHORIZATION "${role}"`,
      );
      await manager.query(
        `ALTER ROLE "${role}" IN DATABASE ${database} SET search_path = "${role}"`,
      );
    });
    return {
      host: this.address.host,
      port: this.address.port,
      database: this.address.database,
      user: role,
      password,
    };
  }

  /** Disconnect the role's sessions, then drop its schema, privileges, and the role itself. */
  async remove(artifactId: string): Promise<void> {
    const role = this.role(artifactId);
    const exists = await this.database.query(
      "SELECT 1 FROM pg_roles WHERE rolname = $1",
      [role],
    );
    if (!(exists as unknown[]).length) return;
    await this.database.query(
      "SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE usename = $1",
      [role],
    );
    await this.database.transaction(async (manager) => {
      await manager.query(`DROP SCHEMA IF EXISTS "${role}" CASCADE`);
      await manager.query(`DROP OWNED BY "${role}"`);
      await manager.query(`DROP ROLE "${role}"`);
    });
  }

  // ===========================================
  // Identifiers
  // ===========================================

  /** The artifact's role name, checked before it is quoted into SQL. */
  private role(artifactId: string): string {
    const role = databaseRoleName(artifactId);
    if (!safeRole.test(role)) throw new Error("Unexpected artifact role name");
    return role;
  }

  /** The artifact data database's name as a quoted identifier. */
  private quotedDatabase(): string {
    return `"${this.address.database.replaceAll('"', '""')}"`;
  }
}
